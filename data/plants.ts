// data/plants.ts

export type PlantType = 'legume' | 'fruit' | 'arbre-fruitier' | 'arbre' | 'arbuste' | 'aromatique' | 'fleur';
export type SunNeed = 'plein-soleil' | 'mi-ombre' | 'ombre';
export type WaterNeed = 'faible' | 'modéré' | 'élevé';
export type Difficulty = 'facile' | 'moyen' | 'difficile';

export interface Plant {
  id: string;
  name: string;
  nameLatin?: string;
  type: PlantType;
  icon: string;
  color: string;
  difficulty: Difficulty;

  // Calendrier (numéros de mois 1–12)
  semisIndoor?: number[];    // semis sous abri / en intérieur
  semisOutdoor?: number[];   // semis en pleine terre
  plantation?: number[];     // plantation (plant, bulbe, bouture)
  harvest?: number[];        // récolte

  // Besoins
  sun: SunNeed;
  watering: WaterNeed;
  soil: string;
  spacing?: string;
  depth?: string;            // profondeur de semis / plantation

  // Durées
  germinationDays?: [number, number];   // [min, max] en jours
  growthWeeks?: [number, number];       // semaines entre plantation et 1ère récolte

  // Rendement estimé
  yieldPerPlant?: string;            // description lisible ("2–4 kg", "50 feuilles"…)
  yieldKgMin?: number;               // rendement min en kg par plant/an
  yieldKgMax?: number;               // rendement max en kg par plant/an

  // Détails culture
  notes: string;
}

