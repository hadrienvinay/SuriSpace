export interface CelestialBody {
  id: string;
  name: string;
  nameFr: string;
  type: 'star' | 'planet' | 'dwarf-planet' | 'moon' | 'asteroid';
  parent?: string; // id du corps parent pour les lunes
  
  // Orbital parameters
  semiMajorAxis?: number; // AU (ou km pour lunes)
  orbitalPeriod?: number; // jours terrestres
  inclination?: number; // degrés
  eccentricity?: number;
  
  // Physical properties
  radius: number; // km
  mass: number; // 10^24 kg
  density?: number; // g/cm³
  gravity?: number; // m/s² surface
  escapeVelocity?: number; // km/s
  rotationPeriod?: number; // heures (négatif = rétrograde)
  axialTilt?: number; // degrés
  
  // Atmosphere
  atmosphereComposition?: { element: string; percent: number }[];
  atmospherePressure?: number; // bar (relative à Terre)
  
  // Composition (masse %)
  composition?: { material: string; percent: number }[];
  
  // Temperatures
  tempMin?: number; // K
  tempMean?: number; // K
  tempMax?: number; // K
  
  // Visual
  color: string; // principal
  colorGradient?: string[]; // pour visuels
  emoji: string;
  
  // Info
  description: string;
  moons?: number; // nombre total de lunes
  rings?: boolean;
  
  // Discovery
  discoveredBy?: string;
  yearDiscovered?: number;
  
  // Notable features
  features?: string[];
}

