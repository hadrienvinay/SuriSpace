export interface FormulaVariable {
  symbol: string;
  meaning: string;
  unit?: string;
}

export interface Formula {
  id: string;
  name: string;
  formula: string;       // Unicode display string
  description: string;
  variables: FormulaVariable[];
  domain: string;
  color: string;
  scientistIds?: string[];   // IDs from scientists.ts
  year?: number;
  keyFact?: string;
}

export interface PhysicsCategory {
  id: string;
  label: string;
  icon: string;
  color: string;
  description: string;
  formulas: Formula[];
}

export interface PhysicsConstant {
  id: string;
  symbol: string;
  nameFr: string;
  value: string;
  unit: string;
  description: string;
  color: string;
  exact?: boolean;
  scientistIds?: string[];
  year?: number;
  category: 'fondamentale' | 'electromag' | 'thermo' | 'mecanique';
}

export interface SIUnit {
  symbol: string;
  nameFr: string;
  quantityFr: string;
  definition: string;
  icon: string;
  color: string;
}

export interface DerivedUnit {
  symbol: string;
  name: string;
  quantity: string;
  inBase: string;
  color: string;
  namedAfter?: string;
}

